// Bundles guides/ (JSON and images) into convex/lib/guideFiles.ts, which
// `GET /guides/*` serves: Convex functions can't read files at run time.
// Run after changing guides/; a test fails while the two differ.
//
//   bun dev/gen-guides.ts

import { guideFiles } from "./guideFiles";

declare const Bun: { write(path: string, text: string): Promise<number> };

const out = new URL("../convex/lib/guideFiles.ts", import.meta.url).pathname;
const entries = (await guideFiles()).map((f) => `  ${JSON.stringify(f.path)}: { type: ${JSON.stringify(f.type)}, etag: ${JSON.stringify(f.etag)}, body: ${JSON.stringify(f.base64)} },`);
await Bun.write(
  out,
  `// Generated by dev/gen-guides.ts from backend/guides; do not edit.\n\nexport type GuideFile = { type: string; etag: string; body: string };\n\nexport const GUIDE_FILES: Record<string, GuideFile> = {\n${entries.join("\n")}\n};\n`,
);
console.log(`guides: ${entries.length} files`);
