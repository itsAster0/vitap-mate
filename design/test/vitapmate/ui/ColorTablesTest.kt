package vitapmate.ui

import androidx.compose.material3.ColorScheme
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.graphics.toArgb
import com.materialkolor.PaletteStyle
import com.materialkolor.dynamicColorScheme
import com.materialkolor.hct.Hct
import com.materialkolor.hct.ViewingConditions
import com.materialkolor.ktx.from
import com.materialkolor.ktx.harmonize
import com.materialkolor.ktx.toneColor
import com.materialkolor.palettes.TonalPalette
import java.io.File
import kotlin.random.Random
import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue

/**
 * ColorTables.kt is Material's colours for [Palette] worked out with materialkolor (a test-only
 * dependency, so the app doesn't ship it). This fails when the table is stale; regenerate with
 * `REGEN_COLORS=1 ./kotlin test -m design`.
 */
class ColorTablesTest {
    private val neutral = Color(0xFF777777)
    private val seeds = listOf(Color(0xFF16A34A), Color(0xFFD97706), Color(0xFFDC2626), Color(0xFF0D9488))

    /** Graphite is black and white controls; the others a tonal spot of their colour. */
    private fun style(p: Palette) = if (p == Palette.Graphite) PaletteStyle.Monochrome else PaletteStyle.TonalSpot

    private fun toneOf(seed: Color, dark: Boolean): List<Color> {
        val palette = TonalPalette.from(seed)
        if (!dark) return listOf(palette.toneColor(40), palette.toneColor(95), palette.toneColor(20))
        val quiet = TonalPalette.fromHueAndChroma(palette.hue, minOf(palette.chroma, 16.0))
        return listOf(palette.toneColor(80), quiet.toneColor(25), palette.toneColor(90))
    }

    private fun hex(c: Color) = "%06X".format(c.toArgb() and 0xFFFFFF)

    /** Ten decimals: the last bits of pow/atan2 differ between CPUs (arm64 laptop, x86 CI). */
    private fun dec(d: Double) = "%.10f".format(java.util.Locale.ROOT, d)

    private fun scheme(s: ColorScheme): String {
        val roles = ColorScheme::class.java.methods
            .filter { it.name.startsWith("get") && it.parameterCount == 0 && it.returnType == Long::class.javaPrimitiveType }
            .map { it.name.removePrefix("get").substringBefore('-').replaceFirstChar(Char::lowercaseChar) to Color((it.invoke(s) as Long).toULong()) }
            .sortedBy { it.first }
        return "ColorScheme(" + roles.joinToString(", ") { (n, c) -> "$n = Color(0xFF${hex(c)})" } + ")"
    }

    @Test
    fun tablesMatchMaterialkolor() {
        val vc = ViewingConditions.DEFAULT
        // The port in ColorTables.kt must match materialkolor's CAM16 hue.
        val rnd = Random(1)
        repeat(5000) {
            val argb = rnd.nextInt() or (0xFF shl 24)
            val want = Hct.fromInt(argb).hue
            val got = cam16Hue(argb, vc.rgbD, vc.fl)
            val d = kotlin.math.abs(want - got).let { minOf(it, 360 - it) }
            assertTrue(d < 0.01, "hue $want vs $got for ${argb.toString(16)}")
        }
        val out = StringBuilder()
        out.appendLine("// Generated once from materialkolor 5.0.1 (dynamicColorScheme, TonalPalette, harmonize) so the")
        out.appendLine("// app ships tables instead of the library.")
        out.appendLine("// Generated by ColorTablesTest (REGEN_COLORS=1 ./kotlin test -m design); do not edit.")
        out.appendLine("package vitapmate.ui")
        out.appendLine()
        out.appendLine("import androidx.compose.material3.ColorScheme")
        out.appendLine("import androidx.compose.ui.graphics.Color")
        out.appendLine()
        out.appendLine("/** [p]'s M3 scheme: light, dark, or dark with black surfaces ([black]). */")
        out.appendLine("internal fun schemeOf(p: Palette, dark: Boolean, black: Boolean): ColorScheme = when (p) {")
        for (p in Palette.entries) {
            val l = dynamicColorScheme(seedColor = p.primary, isDark = false, isAmoled = false, primary = p.primary, neutral = neutral, neutralVariant = neutral, error = seeds[2], style = style(p))
            val d = dynamicColorScheme(seedColor = p.primary, isDark = true, isAmoled = false, primary = p.primary, neutral = neutral, neutralVariant = neutral, error = seeds[2], style = style(p))
            val b = dynamicColorScheme(seedColor = p.primary, isDark = true, isAmoled = true, primary = p.primary, neutral = neutral, neutralVariant = neutral, error = seeds[2], style = style(p))
            out.appendLine("    Palette.${p.name} -> if (!dark) ${scheme(l)}")
            out.appendLine("    else if (!black) ${scheme(d)}")
            out.appendLine("    else ${scheme(b)}")
        }
        out.appendLine("}")
        out.appendLine()
        out.appendLine("/** Each palette's tones, light then dark: accent, success, warning, danger, lab; base, subtle, onSubtle each, as RRGGBB. */")
        out.appendLine("internal val PALETTE_TONES = mapOf(")
        for (p in Palette.entries) {
            val sets = listOf(false, true).map { dark ->
                (listOf(toneOf(p.accent, dark)) + seeds.map { toneOf(it.harmonize(p.accent), dark) }).flatten().joinToString("") { hex(it) }
            }
            out.appendLine("    Palette.${p.name} to listOf(\"${sets[0]}\", \"${sets[1]}\"),")
        }
        out.appendLine(")")
        out.appendLine()
        out.appendLine("/** The status seeds' CAM16 hues: success, warning, danger, lab. */")
        out.appendLine("internal val SEED_HUES = doubleArrayOf(${seeds.joinToString(", ") { dec(Hct.fromInt(it.toArgb()).hue) }})")
        out.appendLine()
        out.appendLine("/**")
        out.appendLine(" * Each status seed's tones (base, subtle, onSubtle as RRGGBB) with its hue turned -15° to +15° in")
        out.appendLine(" * 1° steps, the most harmonizing turns it; light then dark, success, warning, danger, lab.")
        out.appendLine(" */")
        for (dark in listOf(false, true)) {
            val s = seeds.joinToString("") { seed ->
                val h = Hct.fromInt(seed.toArgb())
                (-15..15).joinToString("") { d -> toneOf(Color(Hct.from((h.hue + d + 360) % 360, h.chroma, h.tone).toInt()), dark).joinToString("") { hex(it) } }
            }
            out.appendLine("internal const val TURNED_TONES_${if (dark) "DARK" else "LIGHT"} = \"$s\"")
        }
        out.appendLine()
        out.appendLine("/** CAM16's default viewing conditions (materialkolor's ViewingConditions.DEFAULT). */")
        out.appendLine("internal val CAM16_RGB_D = doubleArrayOf(${vc.rgbD.joinToString(", ") { dec(it) }})")
        out.appendLine("internal const val CAM16_FL = ${dec(vc.fl)}")
        val file = File("").absoluteFile.let { if (it.name == "design") it else it.resolve("design") }.resolve("src/vitapmate/ui/ColorTables.kt")
        if (System.getenv("REGEN_COLORS") == "1") file.writeText(out.toString())
        assertEquals(out.toString(), file.readText(), "ColorTables.kt is stale: REGEN_COLORS=1 ./kotlin test -m design")
        // The turned tones (wallpaper colours) stay within a few levels of the library's.
        var worst = 0
        repeat(3000) {
            val accent = Color(rnd.nextInt() or (0xFF shl 24))
            val hue = cam16Hue(accent.toArgb(), vc.rgbD, vc.fl)
            for (dark in listOf(false, true)) for (seed in seeds) {
                val h = Hct.fromInt(seed.toArgb())
                val diff = 180 - kotlin.math.abs(kotlin.math.abs(h.hue - hue) - 180)
                val dir = if ((hue - h.hue + 360) % 360 <= 180) 1 else -1
                val turn = Math.round(minOf(diff * 0.5, 15.0) * dir).toInt()
                val a = toneOf(seed.harmonize(accent), dark)
                val b = toneOf(Color(Hct.from((h.hue + turn + 360) % 360, h.chroma, h.tone).toInt()), dark)
                a.zip(b).forEach { (x, y) ->
                    val dx = listOf(x.red - y.red, x.green - y.green, x.blue - y.blue).maxOf { kotlin.math.abs(it) * 255 }
                    worst = maxOf(worst, Math.round(dx))
                }
            }
        }
        assertTrue(worst <= 8, "turned tones off by $worst/255")
    }

    /** A copy of `cam16Hue` in Colors.kt (private there), checked against materialkolor above. */
    private fun cam16Hue(argb: Int, rgbD: DoubleArray, fl: Double): Double {
        fun lin(c: Int): Double = (c / 255.0).let { if (it <= 0.040449936) it / 12.92 else Math.pow((it + 0.055) / 1.055, 2.4) } * 100
        val r = lin(argb shr 16 and 0xFF)
        val g = lin(argb shr 8 and 0xFF)
        val b = lin(argb and 0xFF)
        val x = 0.41233895 * r + 0.35762064 * g + 0.18051042 * b
        val y = 0.2126 * r + 0.7152 * g + 0.0722 * b
        val z = 0.01932141 * r + 0.11916382 * g + 0.95034478 * b
        fun adapt(c: Double, d: Double): Double {
            val f = Math.pow(fl * kotlin.math.abs(c * d) / 100, 0.42)
            return Math.signum(c * d) * 400 * f / (f + 27.13)
        }
        val ra = adapt(0.401288 * x + 0.650173 * y - 0.051461 * z, rgbD[0])
        val ga = adapt(-0.250268 * x + 1.204414 * y + 0.045854 * z, rgbD[1])
        val ba = adapt(-0.002079 * x + 0.048952 * y + 0.953127 * z, rgbD[2])
        val a = (11 * ra - 12 * ga + ba) / 11
        val bb = (ra + ga - 2 * ba) / 9
        return (Math.toDegrees(kotlin.math.atan2(bb, a)) + 360) % 360
    }
}
